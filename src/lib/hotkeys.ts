export interface KeyPart {
  /** клавиша или слово-действие */
  text: string
  key: boolean
}

/** «Ctrl+{щелчок} / Alt+W» → варианты, каждый — цепочка клавиш и слов */
export function parseKeys(spec: string): KeyPart[][] {
  return spec.split(' / ').map((alt) => {
    const out: KeyPart[] = []
    for (const piece of alt.split('+')) {
      // внутри части могут идти подряд клавиша и пояснение: «Ctrl+V {с текстом}»
      const re = /\{([^}]*)\}|([^{}\s]+)/g
      let m: RegExpExecArray | null
      while ((m = re.exec(piece))) out.push(m[1] !== undefined ? { text: m[1], key: false } : { text: m[2], key: true })
    }
    return out
  })
}
